package it.polimi.booknest.model;

/**
 * Rappresenta la scelta effettuata da un utente durante uno Showdown.
 * Viene utilizzato per indicare a quale dei due libri in competizione
 * è stato assegnato il voto.
 */
public enum LibroScelto {

    /**
     * Identifica il voto assegnato al primo libro candidato nella sfida.
     */
    A,

    /**
     * Identifica il voto assegnato al secondo libro candidato nella sfida.
     */
    B
}
